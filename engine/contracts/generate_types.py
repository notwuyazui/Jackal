"""Generate the browser contract from the Python dataclasses; --check is read-only."""
from __future__ import annotations
import argparse
import dataclasses
import types
from pathlib import Path
from typing import get_type_hints, get_origin, get_args
from engine.contracts import render

MODELS = [render.Rules, render.MapFrame, render.UnitFrame, render.BulletFrame,
          render.BattleEvent, render.Parameters, render.BattleManifest, render.FrameSnapshot]


def ts_type(value):
    origin, args = get_origin(value), get_args(value)
    if origin is types.UnionType:
        return ' | '.join(ts_type(v) for v in args)
    if origin is tuple:
        if len(args) == 2 and args[1] is Ellipsis:
            item = ts_type(args[0])
            return f'Array<{item}>'
        return '[' + ', '.join(ts_type(v) for v in args) + ']'
    return {int: 'number', float: 'number', bool: 'boolean', str: 'string',
            type(None): 'null'}.get(value, getattr(value, '__name__', str(value)))


def generate():
    out = ['// Generated by python -m engine.contracts.generate_types. Do not edit.\n']
    for model in MODELS:
        hints = get_type_hints(model)
        out.append(f'export interface {model.__name__} {{')
        for f in dataclasses.fields(model):
            out.append(f'  readonly {f.name}: {ts_type(hints[f.name])};')
        out.append('}\n')
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[2] / 'render/render3D/src/generated/engine.ts'
    source = generate()
    if args.check:
        if not target.exists() or target.read_text() != source:
            raise SystemExit('Browser contract differs from the Python dataclasses')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source)

if __name__ == '__main__':
    main()
